#!/usr/bin/env Rscript

###############################################################################
# Author: Iris Sammarco
# Date: 06/10/2026
#
# Run with:
# qsub 02_gene_classes_plot_run.sh
#
# Final Figure 5
#
# Panel A: Number of genes in each transcriptomic response class
#
# Panel B: Model-attributed variance fractions associated with:
#          - Climate
#          - Distribution range
#
# IMPORTANT:
# ---------------------------------------------------------------------------
# This is a plotting-only script.
#
# It does NOT modify or rerun the original gene classes analysis.
#
# It uses the output tables generated by the existing gene classes analysis:
#
#   gene_classification.csv
#   gene_level_variance_partition.csv
#
# Panel B includes:
#
#   Climate panel:
#       Climate-only       -> climate variance shown
#       Climate-and-range  -> climate variance shown
#       Range-only         -> climate variance NOT displayed
#       Non-associated     -> climate variance NOT displayed
#
#   Distribution-range panel:
#       Range-only         -> range variance shown
#       Climate-and-range  -> range variance shown
#       Climate-only       -> range variance NOT displayed
#       Non-associated     -> range variance NOT displayed
#
# The underlying variance-partitioning estimates are NOT changed.
# The figure simply does not display variance for predictor/class
# combinations where the corresponding predictor was not statistically
# associated according to the independent DE-based classification.
#
# Panel A retains all four gene classes.
#
# Figure labels:
#
#   Climate-only
#   Range-only
#   Climate-and-range
#   Non-associated
#
# Outputs:
#
#   Figure5_final.png
#   Figure5_final.pdf
#   Figure5_panelB_plot_data.csv
#
###############################################################################

options(stringsAsFactors = FALSE)

###############################################################################
# 0. Libraries
###############################################################################

suppressPackageStartupMessages({

    library(dplyr)
    library(tidyr)
    library(ggplot2)
    library(readr)
    library(patchwork)

})

###############################################################################
# 1. Configuration
###############################################################################

BASE_DIR <- "/Anastatica"

H4_DIR <- file.path(
    BASE_DIR,
    "climate_range_variance_analysis"
)

TABLE_DIR <- file.path(
    H4_DIR,
    "tables"
)

# New output directory.
#

FIG_DIR <- file.path(
    H4_DIR,
    "figures_final"
)

dir.create(
    FIG_DIR,
    recursive = TRUE,
    showWarnings = FALSE
)

###############################################################################
# 2. Input files
###############################################################################

CLASSIFICATION_FILE <- file.path(
    TABLE_DIR,
    "gene_classification.csv"
)

VARIANCE_FILE <- file.path(
    TABLE_DIR,
    "gene_level_variance_partition.csv"
)

###############################################################################
# 3. Check input files
###############################################################################

if (!file.exists(CLASSIFICATION_FILE)) {

    stop(
        "\nClassification file not found:\n",
        CLASSIFICATION_FILE,
        "\n\nPlease run the original gene classes analysis first."
    )

}

if (!file.exists(VARIANCE_FILE)) {

    stop(
        "\nVariance-partition file not found:\n",
        VARIANCE_FILE,
        "\n\nPlease run the original gene classes analysis first."
    )

}

message("")
message("Input files found.")
message("")

###############################################################################
# 4. Read input data
###############################################################################

gene_class <- read_csv(
    CLASSIFICATION_FILE,
    show_col_types = FALSE
)

vp <- read_csv(
    VARIANCE_FILE,
    show_col_types = FALSE
)

###############################################################################
# 5. Check required columns
###############################################################################

required_classification_columns <- c(
    "GeneID",
    "Category"
)

missing_classification <- setdiff(
    required_classification_columns,
    colnames(gene_class)
)

if (length(missing_classification) > 0) {

    stop(
        "\nThe classification file is missing required columns:\n",
        paste(
            missing_classification,
            collapse = "\n"
        )
    )

}

required_variance_columns <- c(
    "GeneID",
    "V_climate",
    "V_range"
)

missing_variance <- setdiff(
    required_variance_columns,
    colnames(vp)
)

if (length(missing_variance) > 0) {

    stop(
        "\nThe variance file is missing required columns:\n",
        paste(
            missing_variance,
            collapse = "\n"
        )
    )

}

###############################################################################
# 6. Define class labels and ordering
###############################################################################

# Internal class names are retained from the original analysis.
#
# Publication-facing labels are defined here once and then used consistently
# throughout the entire figure.

class_levels <- c(
    "climate_only",
    "range_only",
    "both",
    "neither"
)

class_labels <- c(
    "climate_only" = "Climate-only",
    "range_only"   = "Range-only",
    "both"         = "Climate-and-range",
    "neither"      = "Non-associated"
)

###############################################################################
# 7. Define consistent colours
###############################################################################

# These colours are deliberately reused in:
#
#   Panel A
#   Panel B climate panel
#   Panel B range panel
#
# This means the same class always has the same visual identity.

class_colours <- c(
	"Climate-only"      = "#41ab5d", # green
    "Range-only"        = "#E67E22", # orange
    "Climate-and-range" = "#7A5195", # purple
    "Non-associated"    = "#BDBDBD" # grey
)

###############################################################################
# 8. Prepare classification data
###############################################################################

gene_class_plot <- gene_class %>%

    mutate(

        Category = factor(
            Category,
            levels = class_levels
        ),

        Category_label = recode(
            as.character(Category),
            !!!class_labels
        ),

        Category_label = factor(
            Category_label,
            levels = unname(class_labels)
        )

    )

###############################################################################
# 9. Panel A – raw number of genes
###############################################################################

class_counts <- gene_class_plot %>%

    count(
        Category_label,
        name = "N_genes"
    ) %>%

    # Ensure all four categories are retained even if one happens to have zero
    # genes in another dataset.

    complete(
        Category_label = factor(
            unname(class_labels),
            levels = unname(class_labels)
        ),
        fill = list(
            N_genes = 0
        )
    )

###############################################################################
# 10. Diagnostic output for Panel A
###############################################################################

message("------------------------------------------------------------")
message("Panel A – gene classification counts")
message("------------------------------------------------------------")

print(class_counts)

message("")

###############################################################################
# 11. Prepare variance data
###############################################################################

plot_data <- vp %>%

    select(
        GeneID,
        V_climate,
        V_range
    ) %>%

    left_join(
        gene_class_plot %>%
            select(
                GeneID,
                Category,
                Category_label
            ),
        by = "GeneID"
    )

###############################################################################
# 12. Check matching between classification and variance data
###############################################################################

if (any(is.na(plot_data$Category))) {

    n_missing <- sum(
        is.na(plot_data$Category)
    )

    stop(
        "\n",
        n_missing,
        " genes in the variance table could not be matched ",
        "to the classification table."
    )

}

###############################################################################
# 13. Create Panel B climate data
###############################################################################

# Climate variance is displayed ONLY for:
#
#   Climate-only
#   Climate-and-range
#
# Range-only and Non-associated are deliberately retained as categories
# conceptually but are assigned NA here, so that no boxplot is drawn for
# these combinations.

climate_plot <- plot_data %>%

    mutate(

        VarianceFraction = case_when(

            Category %in% c(
                "climate_only",
                "both"
            ) ~ V_climate,

            TRUE ~ NA_real_

        )

    ) %>%

    filter(
        !is.na(VarianceFraction),
        is.finite(VarianceFraction)
    ) %>%

    transmute(

        GeneID,

        Category,

        Category_label,

        Component = "Climate",

        VarianceFraction

    )

###############################################################################
# 14. Create Panel B distribution-range data
###############################################################################

# Range variance is displayed ONLY for:
#
#   Range-only
#   Climate-and-range
#
# Climate-only and Non-associated are deliberately excluded from the
# corresponding distribution-range variance display.

range_plot <- plot_data %>%

    mutate(

        VarianceFraction = case_when(

            Category %in% c(
                "range_only",
                "both"
            ) ~ V_range,

            TRUE ~ NA_real_

        )

    ) %>%

    filter(
        !is.na(VarianceFraction),
        is.finite(VarianceFraction)
    ) %>%

    transmute(

        GeneID,

        Category,

        Category_label,

        Component = "Distribution range",

        VarianceFraction

    )

###############################################################################
# 15. Combine Panel B plotting data
###############################################################################

panel_b_data <- bind_rows(
    climate_plot,
    range_plot
)

panel_b_data$Component <- factor(
    panel_b_data$Component,
    levels = c(
        "Climate",
        "Distribution range"
    )
)

panel_b_data$Category_label <- factor(
    panel_b_data$Category_label,
    levels = unname(class_labels)
)

###############################################################################
# 16. Save Panel B plotting data
###############################################################################

write_csv(
    panel_b_data,
    file.path(
        FIG_DIR,
        "Figure5_panelB_plot_data.csv"
    )
)

###############################################################################
# 17. Diagnostic output for Panel B
###############################################################################

message("------------------------------------------------------------")
message("Panel B – genes displayed")
message("------------------------------------------------------------")

message(
    "Climate panel:"
)

message(
    "  Climate-only: ",
    sum(
        climate_plot$Category == "climate_only"
    )
)

message(
    "  Climate-and-range: ",
    sum(
        climate_plot$Category == "both"
    )
)

message(
    "  Range-only: not displayed"
)

message(
    "  Non-associated: not displayed"
)

message("")

message(
    "Distribution-range panel:"
)

message(
    "  Range-only: ",
    sum(
        range_plot$Category == "range_only"
    )
)

message(
    "  Climate-and-range: ",
    sum(
        range_plot$Category == "both"
    )
)

message(
    "  Climate-only: not displayed"
)

message(
    "  Non-associated: not displayed"
)

message("")

###############################################################################
# 18. Panel A – gene counts
###############################################################################

p_a <- ggplot(
    class_counts,
    aes(
        x = Category_label,
        y = N_genes,
        fill = Category_label
    )
) +

    geom_col(
        width = 0.72,
        colour = "white",
        linewidth = 0.3
    ) +

    geom_text(
        aes(
            label = format(
                N_genes,
                big.mark = ","
            )
        ),
        vjust = -0.35,
        size = 4
    ) +

    scale_fill_manual(
        values = class_colours,
        drop = FALSE
    ) +

    scale_y_continuous(
        expand = expansion(
            mult = c(
                0,
                0.08
            )
        )
    ) +

    labs(
        x = NULL,
        y = "Number of genes"
    ) +

    theme_bw(
        base_size = 12
    ) +

    theme(

        legend.position = "none",

        plot.title =
            element_text(
                face = "bold",
                size = 13
            ),

        axis.text.x =
            element_text(
                angle = 25,
                hjust = 1,
                vjust = 1
            ),

        panel.grid.major.x =
            element_blank(),

        panel.grid.minor =
            element_blank(),

        plot.margin =
            margin(
                8,
                8,
                8,
                8
            )

    )

###############################################################################
# 19. Panel B – variance fractions
###############################################################################

p_b <- ggplot(
    panel_b_data,
    aes(
        x = Category_label,
        y = VarianceFraction,
        fill = Category_label
    )
) +

    geom_boxplot(
        width = 0.65,

        outlier.shape = 16,

        outlier.size = 1.2,

        outlier.alpha = 0.25,

        colour = "grey25"
    ) +

    facet_wrap(
        ~ Component,
        ncol = 1
    ) +

    scale_fill_manual(
        values = class_colours,
        drop = FALSE
    ) +

    scale_y_continuous(
        limits = c(
            0,
            1
        ),

        breaks = seq(
            0,
            1,
            by = 0.2
        ),

        labels = scales::percent_format(
            accuracy = 1
        ),

        expand = expansion(
            mult = c(
                0,
                0.02
            )
        )
    ) +

    labs(
        x = NULL,
        y = "Model-attributed variance fraction"
    ) +

    theme_bw(
        base_size = 12
    ) +

    theme(

        legend.position = "none",

        plot.title =
            element_text(
                face = "bold",
                size = 13
            ),

        strip.text =
            element_text(
                face = "bold",
                size = 11
            ),

        strip.background =
            element_rect(
                fill = "grey95"
            ),

        axis.text.x =
            element_text(
                angle = 25,
                hjust = 1,
                vjust = 1
            ),

        panel.grid.minor =
            element_blank(),

        panel.grid.major.x =
            element_blank(),

        plot.margin =
            margin(
                8,
                8,
                8,
                8
            )

    )

###############################################################################
# 20. Combine Panel A and Panel B
###############################################################################

# Panel A is intentionally narrower.
#
# Panel B contains the two variance distributions and therefore receives
# more horizontal space.

final_figure <- p_a +
    p_b +

    plot_layout(
        widths = c(
            0.85,
            1.5
        )
    ) +

    plot_annotation(

        tag_levels = "a",

        theme =
            theme(
                plot.tag =
                    element_text(
                        face = "bold",
                        size = 14
                    )
            )

    )

###############################################################################
# 21. Save combined PNG
###############################################################################

ggsave(
    filename = file.path(
        FIG_DIR,
        "Figure5_final.png"
    ),

    plot = final_figure,

    width = 12,

    height = 7.5,

    units = "in",

    dpi = 300,

    bg = "white"
)

###############################################################################
# 22. Save combined PDF
###############################################################################

ggsave(
    filename = file.path(
        FIG_DIR,
        "Figure5_final.pdf"
    ),

    plot = final_figure,

    width = 12,

    height = 7.5,

    units = "in",

    device = cairo_pdf,

    bg = "white"
)

###############################################################################
# 23. Also save individual panels
###############################################################################

ggsave(
    filename = file.path(
        FIG_DIR,
        "Figure5_panelA_gene_counts.png"
    ),

    plot = p_a,

    width = 5.5,

    height = 6.5,

    units = "in",

    dpi = 300,

    bg = "white"
)

ggsave(
    filename = file.path(
        FIG_DIR,
        "Figure5_panelA_gene_counts.pdf"
    ),

    plot = p_a,

    width = 5.5,

    height = 6.5,

    units = "in",

    device = cairo_pdf,

    bg = "white"
)

ggsave(
    filename = file.path(
        FIG_DIR,
        "Figure5_panelB_variance.png"
    ),

    plot = p_b,

    width = 7,

    height = 7.5,

    units = "in",

    dpi = 300,

    bg = "white"
)

ggsave(
    filename = file.path(
        FIG_DIR,
        "Figure5_panelB_variance.pdf"
    ),

    plot = p_b,

    width = 7,

    height = 7.5,

    units = "in",

    device = cairo_pdf,

    bg = "white"
)

###############################################################################
# 24. Display figure
###############################################################################

print(final_figure)

###############################################################################
# 25. Final message
###############################################################################

message("")
message("============================================================")
message("Figure 5 completed successfully")
message("============================================================")
message("")

message(
    "Output directory:\n",
    FIG_DIR
)

message("")

message(
    "Combined PNG:\n",
    file.path(
        FIG_DIR,
        "Figure5_final.png"
    )
)

message("")

message(
    "Combined PDF:\n",
    file.path(
        FIG_DIR,
        "Figure5_final.pdf"
    )
)

message("")

message(
    "Panel A PNG:\n",
    file.path(
        FIG_DIR,
        "Figure5_panelA_gene_counts.png"
    )
)

message("")

message(
    "Panel B PNG:\n",
    file.path(
        FIG_DIR,
        "Figure5_panelB_variance.png"
    )
)

message("")

message(
    "Panel B plotting data:\n",
    file.path(
        FIG_DIR,
        "Figure5_panelB_plot_data.csv"
    )
)

message("")

message("Figure structure:")
message("  (a) Raw number of genes in each response class")
message("  (b) Model-attributed variance fractions")
message("")
message("Panel B climate:")
message("  Climate-only + Climate-and-range")
message("")
message("Panel B distribution range:")
message("  Range-only + Climate-and-range")
message("")
message("Non-associated genes are not displayed in Panel B.")
message("============================================================")